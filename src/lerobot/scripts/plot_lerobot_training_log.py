#!/usr/bin/env python3
"""Parse LeRobot terminal training output and plot its training metrics.

The script is read-only with respect to the log, checkpoints, and dataset.  It
only creates CSV/JSON/PNG analysis artifacts in ``--output-dir``.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import re
from collections import deque
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


PROGRESS_RE = re.compile(r"(?P<step>\d+)\s*/\s*(?P<total>\d+)")
METRICS_RE = re.compile(
    r"\bsmpl:(?P<samples>\S+)\s+"
    r"ep:(?P<episode>\d+)\s+"
    r"epch:(?P<epoch>[-+0-9.eE]+)\s+"
    r"loss:(?P<loss>[-+0-9.eE]+)\s+"
    r"grdn:(?P<gradient_norm>[-+0-9.eE]+)\s+"
    r"lr:(?P<learning_rate>[-+0-9.eE]+)\s+"
    r"updt_s:(?P<update_time_s>[-+0-9.eE]+)\s+"
    r"data_s:(?P<data_time_s>[-+0-9.eE]+)"
)
ANSI_RE = re.compile(r"\x1b\[[0-?]*[ -/]*[@-~]")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("log", type=Path, help="Path to the captured terminal log")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Analysis directory (default: <log directory>/training_analysis)",
    )
    parser.add_argument(
        "--smooth-window",
        type=int,
        default=15,
        help="Number of logged points in the trailing moving average (default: 15)",
    )
    parser.add_argument(
        "--validation-csv",
        type=Path,
        default=None,
        help=(
            "Optional CSV generated by nero_ros2_evaluate_act_checkpoints.py; "
            "adds a training/validation comparison figure"
        ),
    )
    return parser.parse_args()


def parse_log(log_path: Path) -> list[dict[str, int | float | str]]:
    records: dict[int, dict[str, int | float | str]] = {}
    with log_path.open("r", encoding="utf-8", errors="replace") as stream:
        for line_number, raw_line in enumerate(stream, start=1):
            line = ANSI_RE.sub("", raw_line.replace("\r", ""))
            metrics = METRICS_RE.search(line)
            if metrics is None:
                continue

            # The logger abbreviates its own step (for example, 96K), while the
            # tqdm prefix on the same line retains the exact integer step.
            progress_matches = list(PROGRESS_RE.finditer(line[: metrics.start()]))
            if not progress_matches:
                raise ValueError(f"Line {line_number}: metrics found without an exact tqdm step")
            progress = progress_matches[-1]
            step = int(progress.group("step"))
            record: dict[str, int | float | str] = {
                "step": step,
                "total_steps": int(progress.group("total")),
                "samples_label": metrics.group("samples"),
                "episode": int(metrics.group("episode")),
                "epoch": float(metrics.group("epoch")),
                "loss": float(metrics.group("loss")),
                "gradient_norm": float(metrics.group("gradient_norm")),
                "learning_rate": float(metrics.group("learning_rate")),
                "update_time_s": float(metrics.group("update_time_s")),
                "data_time_s": float(metrics.group("data_time_s")),
            }
            records[step] = record

    if not records:
        raise ValueError(f"No LeRobot training metric lines found in {log_path}")
    return [records[step] for step in sorted(records)]


def moving_average(values: list[float], window: int) -> list[float]:
    queue: deque[float] = deque()
    running_sum = 0.0
    result: list[float] = []
    for value in values:
        queue.append(value)
        running_sum += value
        if len(queue) > window:
            running_sum -= queue.popleft()
        result.append(running_sum / len(queue))
    return result


def percentile(values: list[float], fraction: float) -> float:
    ordered = sorted(values)
    position = (len(ordered) - 1) * fraction
    lower = math.floor(position)
    upper = math.ceil(position)
    if lower == upper:
        return ordered[lower]
    return ordered[lower] * (upper - position) + ordered[upper] * (position - lower)


def add_series(
    axis: plt.Axes,
    steps: list[int],
    values: list[float],
    ylabel: str,
    smooth_window: int,
    color: str,
) -> None:
    axis.plot(steps, values, color=color, alpha=0.28, linewidth=0.8, label="logged value")
    axis.plot(
        steps,
        moving_average(values, smooth_window),
        color=color,
        linewidth=1.8,
        label=f"moving average ({smooth_window} points)",
    )
    axis.set_xlabel("Training step")
    axis.set_ylabel(ylabel)
    axis.grid(True, alpha=0.25)
    axis.legend()


def save_plots(records: list[dict[str, int | float | str]], output_dir: Path, window: int) -> None:
    steps = [int(record["step"]) for record in records]
    loss = [float(record["loss"]) for record in records]
    gradient = [float(record["gradient_norm"]) for record in records]
    learning_rate = [float(record["learning_rate"]) for record in records]
    update_time = [float(record["update_time_s"]) for record in records]
    data_time = [float(record["data_time_s"]) for record in records]

    figure, axes = plt.subplots(2, 2, figsize=(14, 9), constrained_layout=True)
    add_series(axes[0, 0], steps, loss, "Loss", window, "tab:blue")
    axes[0, 0].set_title("ACT training loss")
    add_series(axes[0, 1], steps, gradient, "Gradient norm", window, "tab:orange")
    axes[0, 1].set_title("Gradient norm")
    axes[1, 0].plot(steps, learning_rate, color="tab:green", linewidth=1.5)
    axes[1, 0].set(title="Learning rate", xlabel="Training step", ylabel="Learning rate")
    axes[1, 0].grid(True, alpha=0.25)
    axes[1, 1].plot(steps, update_time, label="update", linewidth=1.0)
    axes[1, 1].plot(steps, data_time, label="data", linewidth=1.0)
    axes[1, 1].set(title="Step timing", xlabel="Training step", ylabel="Seconds")
    axes[1, 1].grid(True, alpha=0.25)
    axes[1, 1].legend()
    figure.suptitle("LeRobot ACT training metrics")
    figure.savefig(output_dir / "training_curves.png", dpi=180)
    plt.close(figure)

    for filename, values, ylabel, title, color in (
        ("loss_curve.png", loss, "Loss", "ACT training loss", "tab:blue"),
        ("gradient_norm_curve.png", gradient, "Gradient norm", "Gradient norm", "tab:orange"),
    ):
        figure, axis = plt.subplots(figsize=(12, 5), constrained_layout=True)
        add_series(axis, steps, values, ylabel, window, color)
        axis.set_title(title)
        figure.savefig(output_dir / filename, dpi=180)
        plt.close(figure)


def load_validation_metrics(path: Path) -> list[dict[str, float]]:
    required = {
        "step",
        "first_action_normalized_mae",
        "episode_balanced_normalized_mae_mean",
        "first_action_arm_mae_rad",
        "first_action_gripper_mae",
    }
    with path.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        missing = required - set(reader.fieldnames or [])
        if missing:
            raise ValueError(f"Validation CSV is missing columns: {sorted(missing)}")
        rows = [
            {key: float(value) for key, value in row.items() if key in required}
            for row in reader
        ]
    if not rows:
        raise ValueError(f"Validation CSV contains no rows: {path}")
    return sorted(rows, key=lambda row: row["step"])


def save_training_validation_plot(
    training_records: list[dict[str, int | float | str]],
    validation_rows: list[dict[str, float]],
    output_path: Path,
    smooth_window: int,
) -> None:
    training_steps = [int(record["step"]) for record in training_records]
    training_loss = [float(record["loss"]) for record in training_records]
    checkpoint_steps = [row["step"] for row in validation_rows]

    figure, axes = plt.subplots(2, 2, figsize=(14, 9), constrained_layout=True)
    add_series(
        axes[0, 0],
        training_steps,
        training_loss,
        "Training loss",
        smooth_window,
        "tab:blue",
    )
    axes[0, 0].set_title("Training loss")
    axes[0, 1].plot(
        checkpoint_steps,
        [row["first_action_normalized_mae"] for row in validation_rows],
        marker="o",
        label="frame-weighted",
    )
    axes[0, 1].plot(
        checkpoint_steps,
        [row["episode_balanced_normalized_mae_mean"] for row in validation_rows],
        marker="o",
        label="episode-balanced",
    )
    axes[0, 1].set_title("Validation first-action normalized MAE")
    axes[0, 1].set_ylabel("Normalized MAE")
    axes[0, 1].legend()
    axes[1, 0].plot(
        checkpoint_steps,
        [row["first_action_arm_mae_rad"] for row in validation_rows],
        marker="o",
        color="tab:orange",
    )
    axes[1, 0].set_title("Validation arm MAE")
    axes[1, 0].set_ylabel("Radians")
    axes[1, 1].plot(
        checkpoint_steps,
        [row["first_action_gripper_mae"] for row in validation_rows],
        marker="o",
        color="tab:green",
    )
    axes[1, 1].set_title("Validation gripper MAE")
    axes[1, 1].set_ylabel("Dataset gripper unit")
    for axis in axes.flat:
        axis.set_xlabel("Training/checkpoint step")
        axis.grid(True, alpha=0.25)
    figure.suptitle("Nero ACT training and validation curves")
    figure.savefig(output_path, dpi=180)
    plt.close(figure)


def main() -> None:
    args = parse_args()
    if args.smooth_window < 1:
        raise ValueError("--smooth-window must be at least 1")
    log_path = args.log.expanduser().resolve()
    output_dir = (
        args.output_dir.expanduser().resolve()
        if args.output_dir is not None
        else log_path.parent / "training_analysis"
    )
    records = parse_log(log_path)
    output_dir.mkdir(parents=True, exist_ok=True)

    csv_path = output_dir / "training_metrics.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(records[0]))
        writer.writeheader()
        writer.writerows(records)

    loss = [float(record["loss"]) for record in records]
    gradient = [float(record["gradient_norm"]) for record in records]
    summary = {
        "source_log": str(log_path),
        "record_count": len(records),
        "first_step": int(records[0]["step"]),
        "last_step": int(records[-1]["step"]),
        "logging_interval_steps": (
            int(records[1]["step"]) - int(records[0]["step"]) if len(records) > 1 else None
        ),
        "loss": {
            "first": loss[0],
            "last": loss[-1],
            "minimum": min(loss),
            "minimum_step": int(records[loss.index(min(loss))]["step"]),
            "median": percentile(loss, 0.5),
            "last_25_points_mean": sum(loss[-25:]) / len(loss[-25:]),
        },
        "gradient_norm": {
            "first": gradient[0],
            "last": gradient[-1],
            "minimum": min(gradient),
            "maximum": max(gradient),
            "last_25_points_mean": sum(gradient[-25:]) / len(gradient[-25:]),
        },
        "learning_rate": {
            "first": float(records[0]["learning_rate"]),
            "last": float(records[-1]["learning_rate"]),
        },
        "final_epoch": float(records[-1]["epoch"]),
    }
    (output_dir / "training_summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    save_plots(records, output_dir, args.smooth_window)
    if args.validation_csv is not None:
        validation_path = args.validation_csv.expanduser().resolve()
        validation_rows = load_validation_metrics(validation_path)
        save_training_validation_plot(
            records,
            validation_rows,
            output_dir / "training_validation_curves.png",
            args.smooth_window,
        )
        summary["validation_csv"] = str(validation_path)
        summary["validation_checkpoint_count"] = len(validation_rows)
        (output_dir / "training_summary.json").write_text(
            json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    print(f"Analysis written to: {output_dir}")


if __name__ == "__main__":
    main()
