NERO_TRACKING_TOLERANCE_RAD = 0.02
NERO_TRACKING_STABLE_TIME_S = 0.3
NERO_TRACKING_TIMEOUT_S = 5.0


def wait_for_nero_tracking(
    robot: Robot,
    teleop: Teleoperator | list[Teleoperator] | None,
    events: dict[str, bool],
) -> bool:
    """Wait outside recording until the simulated arm has caught up with the leader."""
    if robot.name != "nero_ros2" or not isinstance(teleop, Teleoperator) or teleop.name != "nero_ros2":
        return True

    position_names = tuple(f"joint{index}.pos" for index in range(1, 8))
    start_t = time.monotonic()
    stable_since: float | None = None
    last_error = float("inf")
    logging.info(
        "等待机械臂追上遥操作器：最大关节误差需连续 %.1fs 小于 %.3frad",
        NERO_TRACKING_STABLE_TIME_S,
        NERO_TRACKING_TOLERANCE_RAD,
    )

    while not events["stop_recording"]:
        observation = robot.get_observation()
        action = teleop.get_action()
        last_error = max(abs(float(observation[name]) - float(action[name])) for name in position_names)
        now = time.monotonic()

        if last_error <= NERO_TRACKING_TOLERANCE_RAD:
            if stable_since is None:
                stable_since = now
            elif now - stable_since >= NERO_TRACKING_STABLE_TIME_S:
                logging.info("机械臂已稳定，最大关节误差 %.4frad，准备开始录制", last_error)
                return True
        else:
            stable_since = None

        if now - start_t >= NERO_TRACKING_TIMEOUT_S:
            raise TimeoutError(
                f"等待机械臂稳定超时（{NERO_TRACKING_TIMEOUT_S:.1f}s），"
                f"当前最大关节误差 {last_error:.4f}rad；为避免写入初始化过程，已取消开始录制"
            )
        time.sleep(0.01)

    return False


class RosTimestampParquetWriter:
    """在官方 LeRobot 数据之外保存每帧对应的 ROS header 时间戳。"""

    SCHEMA = pa.schema(
        [
            ("episode_index", pa.int64()),
            ("frame_index", pa.int64()),
            ("lerobot_timestamp", pa.float64()),
            ("observation_joint_state", pa.int64()),
            ("observation_gripper", pa.int64()),
            ("observation_color", pa.int64()),
            ("observation_depth", pa.int64()),
            ("observation_fisheye", pa.int64()),
            ("action_joint_state", pa.int64()),
            ("action_gripper", pa.int64()),
        ]
    )

    def __init__(self, dataset_root: Path, resume: bool = False):
        del resume  # episode 序号由官方 dataset buffer 决定，无需加载旧时间戳文件。
        self.directory = Path(dataset_root) / "ros_timestamps"
        self.directory.mkdir(parents=True, exist_ok=True)
        self._episode_rows: list[dict[str, int | float]] = []

    def add_frame(
        self,
        episode_index: int,
        frame_index: int,
        lerobot_timestamp: float,
        observation: dict[str, int],
        action: dict[str, int],
    ) -> None:
        self._episode_rows.append(
            {
                "episode_index": int(episode_index),
                "frame_index": int(frame_index),
                "lerobot_timestamp": float(lerobot_timestamp),
                "observation_joint_state": int(observation["joint_state"]),
                "observation_gripper": int(observation["gripper"]),
                "observation_color": int(observation["color"]),
                "observation_depth": int(observation["depth"]),
                "observation_fisheye": int(observation["fisheye"]),
                "action_joint_state": int(action["joint_state"]),
                "action_gripper": int(action["gripper"]),
            }
        )

    def clear_episode(self) -> None:
        self._episode_rows.clear()

    def save_episode(self) -> None:
        if not self._episode_rows:
            return
        episode_indices = {int(row["episode_index"]) for row in self._episode_rows}
        if len(episode_indices) != 1:
            raise RuntimeError(f"一个 ROS 时间戳文件只能包含一个 episode，当前为：{episode_indices}")
        episode_index = episode_indices.pop()
        path = self.directory / f"episode_{episode_index:06d}.parquet"
        if path.exists():
            raise FileExistsError(f"拒绝覆盖已有 ROS 时间戳文件：{path}")
        table = pa.Table.from_pylist(self._episode_rows, schema=self.SCHEMA)
        temporary_path = path.with_suffix(".parquet.tmp")
        pq.write_table(table, temporary_path)
        temporary_path.replace(path)
        self._episode_rows.clear()


@dataclass
class DatasetRecordConfig:
    # Dataset identifier. By convention it should match '{hf_username}/{dataset_name}' (e.g. `lerobot/test`).
    repo_id: str
    # A short but accurate description of the task performed during the recording (e.g. "Pick the Lego block and drop it in the box on the right.")
    single_task: str
    # Root directory where the dataset will be stored (e.g. 'dataset/path'). If None, defaults to $HF_LEROBOT_HOME/repo_id.
    root: str | Path | None = None
    # Limit the frames per second.
    fps: int = 30
    # Number of seconds for data recording for each episode.
    episode_time_s: int | float = 60
    # Number of seconds for resetting the environment after each episode.
    reset_time_s: int | float = 60
    # Number of episodes to record.
    num_episodes: int = 50
    # Encode frames in the dataset into video
    video: bool = True
    # Upload dataset to Hugging Face hub.
    push_to_hub: bool = True
    # Upload on private repository on the Hugging Face hub.
    private: bool = False
    # Add tags to your dataset on the hub.
    tags: list[str] | None = None
    # Number of subprocesses handling the saving of frames as PNG. Set to 0 to use threads only;
    # set to ≥1 to use subprocesses, each using threads to write images. The best number of processes
    # and threads depends on your system. We recommend 4 threads per camera with 0 processes.
    # If fps is unstable, adjust the thread count. If still unstable, try using 1 or more subprocesses.
    num_image_writer_processes: int = 0
    # Number of threads writing the frames as png images on disk, per camera.
    # Too many threads might cause unstable teleoperation fps due to main thread being blocked.
    # Not enough threads might cause low camera fps.
    num_image_writer_threads_per_camera: int = 4
    # Number of episodes to record before batch encoding videos
    # Set to 1 for immediate encoding (default behavior), or higher for batched encoding
    video_encoding_batch_size: int = 1
    # Video codec for encoding videos. Options: 'h264', 'hevc', 'libsvtav1', 'auto',
    # or hardware-specific: 'h264_videotoolbox', 'h264_nvenc', 'h264_vaapi', 'h264_qsv'.
    # Use 'auto' to auto-detect the best available hardware encoder.
    vcodec: str = "libsvtav1"
    # Enable streaming video encoding: encode frames in real-time during capture instead
    # of writing PNG images first. Makes save_episode() near-instant. More info in the documentation: https://huggingface.co/docs/lerobot/streaming_video_encoding
    streaming_encoding: bool = False
    # Maximum number of frames to buffer per camera when using streaming encoding.
    # ~1s buffer at 30fps. Provides backpressure if the encoder can't keep up.
    encoder_queue_maxsize: int = 30
    # Number of threads per encoder instance. None = auto (codec default).
    # Lower values reduce CPU usage, maps to 'lp' (via svtav1-params) for libsvtav1 and 'threads' for h264/hevc..
    encoder_threads: int | None = None
    # Rename map for the observation to override the image and state keys
    rename_map: dict[str, str] = field(default_factory=dict)

    def __post_init__(self):
        if self.single_task is None:
            raise ValueError("You need to provide a task as argument in `single_task`.")


@dataclass
class RecordConfig:
    robot: RobotConfig
    dataset: DatasetRecordConfig
    # Whether to control the robot with a teleoperator
    teleop: TeleoperatorConfig | None = None
    # Whether to control the robot with a policy
    policy: PreTrainedConfig | None = None
    # Display all cameras on screen
    display_data: bool = False
    # Display data on a remote Rerun server
    display_ip: str | None = None
    # Port of the remote Rerun server
    display_port: int | None = None
    # Whether to  display compressed images in Rerun
    display_compressed_images: bool = False
    # Use vocal synthesis to read events.
    play_sounds: bool = True
    # Resume recording on an existing dataset.
    resume: bool = False

    def __post_init__(self):
        # HACK: We parse again the cli args here to get the pretrained path if there was one.
        policy_path = parser.get_path_arg("policy")

        if policy_path:
            cli_overrides = parser.get_cli_overrides("policy")

            self.policy = PreTrainedConfig.from_pretrained(policy_path, cli_overrides=cli_overrides)
            self.policy.pretrained_path = policy_path

        if self.teleop is None and self.policy is None:
            raise ValueError("Choose a policy, a teleoperator or both to control the robot")

    @classmethod
    def __get_path_fields__(cls) -> list[str]:
        """This enables the parser to load config from the policy using `--policy.path=local/dir`"""
        return ["policy"]


""" --------------- record_loop() data flow --------------------------
       [ Robot ]
           V
     [ robot.get_observation() ] ---> raw_obs
           V
     [ robot_observation_processor ] ---> processed_obs
           V
     .-----( ACTION LOGIC )------------------.
     V                                       V
     [ From Teleoperator ]                   [ From Policy ]
     |                                       |
     |  [teleop.get_action] -> raw_action    |   [predict_action]
     |          |                            |          |
     |          V                            |          V
     | [teleop_action_processor]             |          |
     |          |                            |          |
     '---> processed_teleop_action           '---> processed_policy_action
     |                                       |
     '-------------------------.-------------'
                               V
                  [ robot_action_processor ] --> robot_action_to_send
                               V
                    [ robot.send_action() ] -- (Robot Executes)
                               V
                    ( Save to Dataset )
                               V
                  ( Rerun Log / Loop Wait )
"""


@safe_stop_image_writer
def record_loop(
    robot: Robot,
    events: dict,
    fps: int,
    teleop_action_processor: RobotProcessorPipeline[
        tuple[RobotAction, RobotObservation], RobotAction
    ],  # runs after teleop
    robot_action_processor: RobotProcessorPipeline[
        tuple[RobotAction, RobotObservation], RobotAction
    ],  # runs before robot
    robot_observation_processor: RobotProcessorPipeline[
        RobotObservation, RobotObservation
    ],  # runs after robot
    dataset: LeRobotDataset | None = None,
    teleop: Teleoperator | list[Teleoperator] | None = None,
    policy: PreTrainedPolicy | None = None,
    preprocessor: PolicyProcessorPipeline[dict[str, Any], dict[str, Any]] | None = None,
    postprocessor: PolicyProcessorPipeline[PolicyAction, PolicyAction] | None = None,
    control_time_s: int | None = None,
    single_task: str | None = None,
    display_data: bool = False,
    display_compressed_images: bool = False,
    ros_timestamp_writer: RosTimestampParquetWriter | None = None,
):
    if dataset is not None and dataset.fps != fps:
        raise ValueError(f"The dataset fps should be equal to requested fps ({dataset.fps} != {fps}).")

    teleop_arm = teleop_keyboard = None
    if isinstance(teleop, list):
        teleop_keyboard = next((t for t in teleop if isinstance(t, KeyboardTeleop)), None)
        teleop_arm = next(
            (
                t
                for t in teleop
                if isinstance(
                    t,
                    (
                        so_leader.SO100Leader
                        | so_leader.SO101Leader
                        | koch_leader.KochLeader
                        | omx_leader.OmxLeader
                    ),
                )
            ),
            None,
        )

        if not (teleop_arm and teleop_keyboard and len(teleop) == 2 and robot.name == "lekiwi_client"):
            raise ValueError(
                "For multi-teleop, the list must contain exactly one KeyboardTeleop and one arm teleoperator. Currently only supported for LeKiwi robot."
            )

    # Reset policy and processor if they are provided
    if policy is not None and preprocessor is not None and postprocessor is not None:
        policy.reset()
        preprocessor.reset()
        postprocessor.reset()

    no_action_count = 0
    timestamp = 0
    start_episode_t = time.perf_counter()
    if dataset is not None:
        logging.info(
            "========== 正式开始录制 episode %s（第一帧即将写入）==========",
            dataset.num_episodes,
        )
    while timestamp < control_time_s:
        start_loop_t = time.perf_counter()

        if events["exit_early"]:
            events["exit_early"] = False
            break

        # Get robot observation
        obs = robot.get_observation()
        observation_ros_timestamps = (
            robot.get_observation_timestamps() if ros_timestamp_writer is not None else None
        )
        action_ros_timestamps = None

        # Applies a pipeline to the raw robot observation, default is IdentityProcessor
        obs_processed = robot_observation_processor(obs)

        if policy is not None or dataset is not None:
            observation_frame = build_dataset_frame(dataset.features, obs_processed, prefix=OBS_STR)

        # Get action from either policy or teleop
        if policy is not None and preprocessor is not None and postprocessor is not None:
            action_values = predict_action(
                observation=observation_frame,
                policy=policy,
                device=get_safe_torch_device(policy.config.device),
                preprocessor=preprocessor,
                postprocessor=postprocessor,
                use_amp=policy.config.use_amp,
                task=single_task,
                robot_type=robot.robot_type,
            )

            act_processed_policy: RobotAction = make_robot_action(action_values, dataset.features)

        elif policy is None and isinstance(teleop, Teleoperator):
            act = teleop.get_action()
            action_ros_timestamps = (
                teleop.get_action_timestamps() if ros_timestamp_writer is not None else None
            )

            # Applies a pipeline to the raw teleop action, default is IdentityProcessor
            act_processed_teleop = teleop_action_processor((act, obs))

        elif policy is None and isinstance(teleop, list):
            arm_action = teleop_arm.get_action()
            arm_action = {f"arm_{k}": v for k, v in arm_action.items()}
            keyboard_action = teleop_keyboard.get_action()
            base_action = robot._from_keyboard_to_base_action(keyboard_action)
            act = {**arm_action, **base_action} if len(base_action) > 0 else arm_action
            act_processed_teleop = teleop_action_processor((act, obs))
        else:
            no_action_count += 1
            if no_action_count == 1 or no_action_count % 10 == 0:
                logging.warning(
                    "No policy or teleoperator provided, skipping action generation. "
                    "This is likely to happen when resetting the environment without a teleop device. "
                    "The robot won't be at its rest position at the start of the next episode."
                )
            continue

        # Applies a pipeline to the action, default is IdentityProcessor
        if policy is not None and act_processed_policy is not None:
            action_values = act_processed_policy
            robot_action_to_send = robot_action_processor((act_processed_policy, obs))
        else:
            action_values = act_processed_teleop
            robot_action_to_send = robot_action_processor((act_processed_teleop, obs))

        # Send action to robot
        # Action can eventually be clipped using `max_relative_target`,
        # so action actually sent is saved in the dataset. action = postprocessor.process(action)
        # TODO(steven, pepijn, adil): we should use a pipeline step to clip the action, so the sent action is the action that we input to the robot.
        _sent_action = robot.send_action(robot_action_to_send)

        # Write to dataset
        if dataset is not None:
            if robot.name == "nero_ros2" and dataset.episode_buffer["size"] == 0:
                position_names = tuple(f"joint{index}.pos" for index in range(1, 8)) + ("gripper.pos",)
                start_observation = [round(float(obs_processed[name]), 5) for name in position_names]
                start_action = [round(float(action_values[name]), 5) for name in position_names]
                arm_error = max(
                    abs(float(obs_processed[name]) - float(action_values[name]))
                    for name in position_names[:-1]
                )
                logging.info(
                    "episode %s 首帧位置（写入前）：observation=%s action=%s 最大手臂误差=%.5frad",
                    dataset.num_episodes,
                    start_observation,
                    start_action,
                    arm_error,
                )
            action_frame = build_dataset_frame(dataset.features, action_values, prefix=ACTION)
            frame = {**observation_frame, **action_frame, "task": single_task}
            dataset.add_frame(frame)
            if ros_timestamp_writer is not None:
                if observation_ros_timestamps is None or action_ros_timestamps is None:
                    raise RuntimeError("ROS 时间戳写入已启用，但当前帧缺少 observation 或 action 时间戳")
                ros_timestamp_writer.add_frame(
                    episode_index=dataset.episode_buffer["episode_index"],
                    frame_index=dataset.episode_buffer["frame_index"][-1],
                    lerobot_timestamp=dataset.episode_buffer["timestamp"][-1],
                    observation=observation_ros_timestamps,
                    action=action_ros_timestamps,
                )

        if display_data:
            log_rerun_data(
                observation=obs_processed, action=action_values, compress_images=display_compressed_images
            )

        dt_s = time.perf_counter() - start_loop_t

        sleep_time_s: float = 1 / fps - dt_s
        if sleep_time_s < 0:
            logging.warning(
                f"Record loop is running slower ({1 / dt_s:.1f} Hz) than the target FPS ({fps} Hz). Dataset frames might be dropped and robot control might be unstable. Common causes are: 1) Camera FPS not keeping up 2) Policy inference taking too long 3) CPU starvation"
            )

        precise_sleep(max(sleep_time_s, 0.0))

        timestamp = time.perf_counter() - start_episode_t


@parser.wrap()
def record(cfg: RecordConfig) -> LeRobotDataset:
    init_logging()
    logging.info(pformat(asdict(cfg)))
    if cfg.display_data:
        init_rerun(session_name="recording", ip=cfg.display_ip, port=cfg.display_port)
    display_compressed_images = (
        True
        if (cfg.display_data and cfg.display_ip is not None and cfg.display_port is not None)
        else cfg.display_compressed_images
    )

    robot = make_robot_from_config(cfg.robot)
    teleop = make_teleoperator_from_config(cfg.teleop) if cfg.teleop is not None else None

    teleop_action_processor, robot_action_processor, robot_observation_processor = make_default_processors()

    dataset_features = combine_feature_dicts(
        aggregate_pipeline_dataset_features(
            pipeline=teleop_action_processor,
            initial_features=create_initial_features(
                action=robot.action_features
            ),  # TODO(steven, pepijn): in future this should be come from teleop or policy
            use_videos=cfg.dataset.video,
        ),
        aggregate_pipeline_dataset_features(
            pipeline=robot_observation_processor,
            initial_features=create_initial_features(observation=robot.observation_features),
            use_videos=cfg.dataset.video,
        ),
    )

    dataset = None
    listener = None

    try:
        if cfg.resume:
            dataset = LeRobotDataset(
                cfg.dataset.repo_id,
                root=cfg.dataset.root,
                batch_encoding_size=cfg.dataset.video_encoding_batch_size,
                vcodec=cfg.dataset.vcodec,
                streaming_encoding=cfg.dataset.streaming_encoding,
                encoder_queue_maxsize=cfg.dataset.encoder_queue_maxsize,
                encoder_threads=cfg.dataset.encoder_threads,
            )

            if hasattr(robot, "cameras") and len(robot.cameras) > 0:
                dataset.start_image_writer(
                    num_processes=cfg.dataset.num_image_writer_processes,
                    num_threads=cfg.dataset.num_image_writer_threads_per_camera * len(robot.cameras),
                )
            sanity_check_dataset_robot_compatibility(dataset, robot, cfg.dataset.fps, dataset_features)
        else:
            # Create empty dataset or load existing saved episodes
            sanity_check_dataset_name(cfg.dataset.repo_id, cfg.policy)
            dataset = LeRobotDataset.create(
                cfg.dataset.repo_id,
                cfg.dataset.fps,
                root=cfg.dataset.root,
                robot_type=robot.name,
                features=dataset_features,
                use_videos=cfg.dataset.video,
                image_writer_processes=cfg.dataset.num_image_writer_processes,
                image_writer_threads=cfg.dataset.num_image_writer_threads_per_camera * len(robot.cameras),
                batch_encoding_size=cfg.dataset.video_encoding_batch_size,
                vcodec=cfg.dataset.vcodec,
                streaming_encoding=cfg.dataset.streaming_encoding,
                encoder_queue_maxsize=cfg.dataset.encoder_queue_maxsize,
                encoder_threads=cfg.dataset.encoder_threads,
            )

        ros_timestamp_writer = None
        if robot.name == "nero_ros2" and teleop is not None and teleop.name == "nero_ros2":
            required_interfaces = (
                (robot, "get_observation_timestamps"),
                (teleop, "get_action_timestamps"),
            )
            missing_interfaces = [name for device, name in required_interfaces if not hasattr(device, name)]
            if missing_interfaces:
                raise RuntimeError(f"Nero ROS 时间戳接口缺失：{missing_interfaces}")
            if cfg.policy is not None:
                logging.warning("使用 policy 时没有 ROS action 话题时间戳，因此不创建旁路时间戳 Parquet")
            else:
                ros_timestamp_writer = RosTimestampParquetWriter(dataset.root, resume=cfg.resume)
                logging.info("每个 episode 的 ROS 时间戳将分别写入 %s", ros_timestamp_writer.directory)

        # Load pretrained policy
        policy = None if cfg.policy is None else make_policy(cfg.policy, ds_meta=dataset.meta)
        preprocessor = None
        postprocessor = None
        if cfg.policy is not None:
            preprocessor, postprocessor = make_pre_post_processors(
                policy_cfg=cfg.policy,
                pretrained_path=cfg.policy.pretrained_path,
                dataset_stats=rename_stats(dataset.meta.stats, cfg.dataset.rename_map),
                preprocessor_overrides={
                    "device_processor": {"device": cfg.policy.device},
                    "rename_observations_processor": {"rename_map": cfg.dataset.rename_map},
                },
            )

        robot.connect()
        if teleop is not None:
            teleop.connect()

        listener, events = init_keyboard_listener()

        if not cfg.dataset.streaming_encoding:
            logging.info(
                "Streaming encoding is disabled. If you have capable hardware, consider enabling it for way faster episode saving. --dataset.streaming_encoding=true --dataset.encoder_threads=2 # --dataset.vcodec=auto. More info in the documentation: https://huggingface.co/docs/lerobot/streaming_video_encoding"
            )

        with VideoEncodingManager(dataset):
            recorded_episodes = 0

            # Randomize the first episode too. Later episodes are reset by F8 below.
            if robot.name == "nero_ros2":
                log_say("Reset the environment", cfg.play_sounds)
                robot.reset()
                wait_for_nero_tracking(robot, teleop, events)

            while recorded_episodes < cfg.dataset.num_episodes and not events["stop_recording"]:
                log_say(f"Recording episode {dataset.num_episodes}", cfg.play_sounds)
                record_loop(
                    robot=robot,
                    events=events,
                    fps=cfg.dataset.fps,
                    teleop_action_processor=teleop_action_processor,
                    robot_action_processor=robot_action_processor,
                    robot_observation_processor=robot_observation_processor,
                    teleop=teleop,
                    policy=policy,
                    preprocessor=preprocessor,
                    postprocessor=postprocessor,
                    dataset=dataset,
                    control_time_s=cfg.dataset.episode_time_s,
                    single_task=cfg.dataset.single_task,
                    display_data=cfg.display_data,
                    display_compressed_images=display_compressed_images,
                    ros_timestamp_writer=ros_timestamp_writer,
                )

                # F8 is a one-key episode boundary for reset-capable simulation robots.
                # Reset before the blocking save so scene randomization is immediate and
                # video encoding time is also useful settling time for the next episode.
                if events["reset_environment"]:
                    events["reset_environment"] = False
                    events["exit_early"] = False

                    # Reset first so the user sees the new randomized scene immediately.
                    # Saving/encoding the completed episode can then overlap with the
                    # simulator settling at the leader's current pose.
                    has_next_episode = recorded_episodes + 1 < cfg.dataset.num_episodes
                    if has_next_episode and not events["stop_recording"]:
                        reset = getattr(robot, "reset", None)
                        if not callable(reset):
                            raise RuntimeError(
                                f"Robot {robot.name!r} does not provide reset(), but F8 environment reset was requested"
                            )
                        log_say("Reset the environment", cfg.play_sounds)
                        reset()

                    dataset.save_episode()
                    if ros_timestamp_writer is not None:
                        ros_timestamp_writer.save_episode()
                    recorded_episodes += 1

                    if has_next_episode and not events["stop_recording"]:
                        wait_for_nero_tracking(robot, teleop, events)
                    continue

                # Execute a few seconds without recording to give time to manually reset the environment
                # Skip reset for the last episode to be recorded
                if not events["stop_recording"] and (
                    (recorded_episodes < cfg.dataset.num_episodes - 1) or events["rerecord_episode"]
                ):
                    log_say("Reset the environment", cfg.play_sounds)

                    # reset g1 robot
                    if robot.name == "unitree_g1":
                        robot.reset()

                    record_loop(
                        robot=robot,
                        events=events,
                        fps=cfg.dataset.fps,
                        teleop_action_processor=teleop_action_processor,
                        robot_action_processor=robot_action_processor,
                        robot_observation_processor=robot_observation_processor,
                        teleop=teleop,
                        control_time_s=cfg.dataset.reset_time_s,
                        single_task=cfg.dataset.single_task,
                        display_data=cfg.display_data,
                    )

                    # F8 may also arrive during the legacy manual-reset window. Consume it
                    # here so it cannot immediately terminate an empty next episode.
                    if events["reset_environment"]:
                        events["reset_environment"] = False
                        events["exit_early"] = False
                        reset = getattr(robot, "reset", None)
                        if not callable(reset):
                            raise RuntimeError(
                                f"Robot {robot.name!r} does not provide reset(), but F8 environment reset was requested"
                            )
                        reset()

                if events["rerecord_episode"]:
                    log_say("Re-record episode", cfg.play_sounds)
                    events["rerecord_episode"] = False
                    events["exit_early"] = False
                    dataset.clear_episode_buffer()
                    if ros_timestamp_writer is not None:
                        ros_timestamp_writer.clear_episode()
                    continue

                dataset.save_episode()
                if ros_timestamp_writer is not None:
                    ros_timestamp_writer.save_episode()
                recorded_episodes += 1
    finally:
        log_say("Stop recording", cfg.play_sounds, blocking=True)

        if dataset:
            dataset.finalize()

        if robot.is_connected:
            robot.disconnect()
        if teleop and teleop.is_connected:
            teleop.disconnect()

        if not is_headless() and listener:
            listener.stop()

        if cfg.dataset.push_to_hub:
            dataset.push_to_hub(tags=cfg.dataset.tags, private=cfg.dataset.private)

        log_say("Exiting", cfg.play_sounds)
    return dataset


def main():
    register_third_party_plugins()
    record()


if __name__ == "__main__":
    main()
